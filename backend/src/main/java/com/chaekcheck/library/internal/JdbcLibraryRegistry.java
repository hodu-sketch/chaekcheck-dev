package com.chaekcheck.library.internal;

import java.util.List;

import org.springframework.jdbc.core.simple.JdbcClient;
import org.springframework.stereotype.Component;
import org.springframework.transaction.annotation.Propagation;
import org.springframework.transaction.annotation.Transactional;

import com.chaekcheck.library.LendingModel;
import com.chaekcheck.library.LibraryRegistry;
import com.chaekcheck.library.NewEligibilityRule;
import com.chaekcheck.library.NewLibrary;
import com.chaekcheck.library.PlatformType;
import com.chaekcheck.library.RegisteredLibrary;
import com.chaekcheck.library.Vendor;

/**
 * {@link LibraryRegistry} in SQL (cycle 13, ADR-0083). The {@link Library} entity stays read-only; rows go in with
 * plain INSERTs, ids given. {@code library.library.id} is {@code GENERATED BY DEFAULT AS IDENTITY}, so an id may be
 * given; the identity sequence is then moved past it.
 */
@Component
class JdbcLibraryRegistry implements LibraryRegistry {

	private static final String SEQUENCE = "SELECT pg_get_serial_sequence('library.library', 'id')";

	private final JdbcClient jdbc;

	JdbcLibraryRegistry(JdbcClient jdbc) {
		this.jdbc = jdbc;
	}

	@Override
	@Transactional(propagation = Propagation.MANDATORY)
	public void add(List<NewLibrary> libraries) {
		if (libraries.isEmpty()) {
			return;
		}
		for (NewLibrary library : libraries) {
			jdbc.sql("""
					INSERT INTO library.library (id, name, platform_type, vendor, lending_model, order_no, base_url,
					  homepage_url, eligibility_summary, extra_condition_text, visit_required, join_method, join_url,
					  join_caution, join_notice, holdings_count, holdings_counted_on, deferred, join_survey)
					VALUES (:id, :name, :platformType, :vendor, :lendingModel, :orderNo, :baseUrl, :homepageUrl,
					  :eligibilitySummary, :extraConditionText, :visitRequired, :joinMethod, :joinUrl, :joinCaution,
					  :joinNotice, :holdingsCount, :holdingsCountedOn, :deferred, :joinSurvey)""")
				.param("id", library.id())
				.param("name", library.name())
				.param("platformType", name(library.platformType()))
				.param("vendor", name(library.vendor()))
				.param("lendingModel", name(library.lendingModel()))
				.param("orderNo", library.orderNo())
				.param("baseUrl", library.baseUrl())
				.param("homepageUrl", library.homepageUrl())
				.param("eligibilitySummary", library.eligibilitySummary())
				.param("extraConditionText", library.extraConditionText())
				.param("visitRequired", library.visitRequired())
				.param("joinMethod", library.joinMethod())
				.param("joinUrl", library.joinUrl())
				.param("joinCaution", library.joinCaution())
				.param("joinNotice", library.joinNotice())
				.param("holdingsCount", library.holdingsCount())
				.param("holdingsCountedOn", library.holdingsCountedOn())
				.param("deferred", library.deferred())
				.param("joinSurvey", name(library.joinSurvey()))
				.update();
			for (NewEligibilityRule rule : library.rules()) {
				jdbc.sql("""
						INSERT INTO library.eligibility_rule (library_id, basis, scope_type, scope_region_id)
						VALUES (:libraryId, :basis, :scopeType, :scopeRegionId)""")
					.param("libraryId", library.id())
					.param("basis", rule.basis())
					.param("scopeType", rule.scopeType())
					.param("scopeRegionId", rule.scopeRegionId())
					.update();
			}
		}
		// past the highest id, never back: setval(n) makes the next value n + 1
		String sequence = sequence();
		jdbc.sql("SELECT setval('" + sequence + "', GREATEST((SELECT max(id) FROM library.library), "
				+ "(SELECT CASE WHEN is_called THEN last_value ELSE last_value - 1 END FROM " + sequence + ")))")
			.query(Long.class)
			.single();
	}

	@Override
	@Transactional(readOnly = true)
	public long nextId() {
		String sequence = sequence();
		return jdbc.sql("SELECT GREATEST(coalesce((SELECT max(id) FROM library.library), 0) + 1, "
				+ "(SELECT CASE WHEN is_called THEN last_value + 1 ELSE last_value END FROM " + sequence + "))")
			.query(Long.class)
			.single();
	}

	@Override
	@Transactional(readOnly = true)
	public List<RegisteredLibrary> listAll() {
		return jdbc.sql("""
				SELECT id, name, base_url, platform_type, vendor, lending_model, order_no, enabled
				FROM library.library ORDER BY id""")
			.query((rs, n) -> new RegisteredLibrary(rs.getLong("id"), rs.getString("name"), rs.getString("base_url"),
					value(PlatformType.class, rs.getString("platform_type")), value(Vendor.class, rs.getString("vendor")),
					value(LendingModel.class, rs.getString("lending_model")), rs.getInt("order_no"),
					rs.getBoolean("enabled")))
			.list();
	}

	/** The identity sequence's name from the catalog (schema-qualified, quoted when needed). */
	private String sequence() {
		return jdbc.sql(SEQUENCE).query(String.class).single();
	}

	private static String name(Enum<?> value) {
		return value == null ? null : value.name();
	}

	private static <E extends Enum<E>> E value(Class<E> type, String name) {
		return name == null ? null : Enum.valueOf(type, name);
	}

}
