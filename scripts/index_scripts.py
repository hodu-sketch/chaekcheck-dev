"""Script lists for scripts/: each script's one-line summary from its own header and the docs that name it.
Run from the repo root after adding or renaming a script: python scripts/index_scripts.py
It rewrites only the block between the script-list markers in each folder README.md (hand-written parts stay).
"""
import collections
import posixpath
import re
import subprocess

BEGIN = '<!-- script-list: generated by scripts/index_scripts.py, do not edit by hand -->'
END = '<!-- /script-list -->'
EXT = re.compile(r'\.(py|ps1|sh|sql|mjs|js|cmd|java)$')


def git_files(*spec):
    out = subprocess.run(['git', 'ls-files', '-z', *spec], capture_output=True).stdout.decode('utf-8')
    return [f for f in out.split('\0') if f]


scripts = [f for f in git_files('scripts') if EXT.search(f) and '/lists/' not in f and '/testdata/' not in f]
mds = git_files('*.md')
md_text = {f: open(f, encoding='utf-8', errors='replace').read() for f in mds}


def summary(path):
    """First sentence of the header comment or docstring."""
    text = open(path, encoding='utf-8', errors='replace').read()
    lines = text.splitlines()
    buf = []
    m = re.search(r'^\s*r?("""|\'\'\')(.*?)(\1)', text, re.S | re.M)
    javadoc = re.search(r'/\*\*(.*?)\*/', text, re.S) if path.endswith('.java') else None
    if m and text[:m.start()].count('\n') < 15:
        buf = m.group(2).strip().splitlines()
    elif javadoc:
        buf = [re.sub(r'\{@code ([^}]*)\}', r'\1', re.sub(r'^\s*\*\s?', '', l)) for l in javadoc.group(1).strip().splitlines()]
    else:
        for l in lines[:20]:
            s = l.strip()
            if s.startswith(('#!', '# -*-')) or s.lower().startswith('@echo') or not s:
                if buf:
                    break
                continue
            if s.startswith(('#', '//', '--', '::', '<#')) or s.lower().startswith('rem'):
                buf.append(re.sub(r'^(#+|//|--|::|<#|[Rr][Ee][Mm])\s?', '', s))
            elif buf:
                break
    para = []
    for l in buf:
        if not l.strip():
            if para:
                break
            continue
        para.append(l.strip())
    s = ' '.join(para)
    cut = re.search(r'(?<=[.!?。])\s|(?<=다\.)\s', s)
    if cut and cut.start() > 30:
        s = s[:cut.start()]
    if len(s) > 220:
        s = s[:217].rstrip() + '…'
    return s.replace('|', '\\|').replace('~', '\\~') or '(설명 없음)'


def docs_for(path):
    name = posixpath.basename(path)
    hits = [m for m, t in md_text.items() if name in t and not m.startswith('scripts/')]
    good = [m for m in hits if not m.startswith('docs/cycles/') and 'RULES' not in m]
    return good or hits


def rel(frm_dir, to):
    return posixpath.relpath(to, frm_dir)


def doc_label(m):
    return posixpath.basename(m) if not m.endswith('README.md') else posixpath.dirname(m).split('/')[-1] + '/README.md'


def table(folder, items, cols_docs=2):
    rows = ['| 파일 | 하는 일 | 설명 문서 |', '|---|---|---|']
    for p in items:
        docs = docs_for(p)[:cols_docs]
        links = ', '.join(f'[{doc_label(d)}]({rel(folder, d)})' for d in docs) or '—'
        rows.append(f'| [`{posixpath.basename(p)}`]({posixpath.basename(p)}) | {summary(p)} | {links} |')
    return rows


by_folder = collections.defaultdict(list)
for s in sorted(scripts):
    by_folder[posixpath.dirname(s)].append(s)


def put_block(readme, body_lines, intro=None, title=None):
    block = BEGIN + '\n' + '\n'.join(body_lines) + '\n' + END
    try:
        text = open(readme, encoding='utf-8').read()
    except FileNotFoundError:
        text = f'# {title}\n\n{intro}\n'
    if BEGIN in text:
        text = re.sub(re.escape(BEGIN) + '.*?' + re.escape(END), lambda m: block, text, flags=re.S)
    else:
        text = text.rstrip('\n') + '\n\n## 스크립트 전체 목록\n\n' + block + '\n'
    open(readme, 'w', encoding='utf-8', newline='\n').write(text)


