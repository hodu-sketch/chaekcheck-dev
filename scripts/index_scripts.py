def group_by_report(folder, items):
    """aisearch/eval: one heading per report that explains the scripts, in date order."""
    groups = collections.defaultdict(list)
    for p in items:
        docs = [d for d in docs_for(p) if '/reports/' in d] or docs_for(p)
        groups[docs[0] if docs else ''].append(p)
    lines = []
    for doc in sorted(groups, key=lambda d: (d == '', posixpath.basename(d))):
        head = f'[{doc_label(doc)}]({rel(folder, doc)})' if doc else '설명 문서 없음'
        lines += ['', f'### {head}', ''] + table(folder, groups[doc])
    return lines[1:]


def main():
    for folder, items in by_folder.items():
        readme = folder + '/README.md'
        if folder == 'scripts':
            continue
        if folder == 'scripts/aisearch/eval':
            put_block(readme, ['스크립트를 설명하는 보고서별로 묶었습니다(보고서가 없으면 그 스크립트를 처음 이름 댄 문서).', ''] + group_by_report(folder, items))
            continue
        title, intro = NEW_READMES.get(folder, (None, None))
        put_block(readme, table(folder, items), intro=intro, title=title)
    # top-level scripts go in scripts/README.md
    put_block('scripts/README.md', table('scripts', by_folder['scripts']))


if __name__ == '__main__':
    main()
